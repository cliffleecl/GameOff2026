export const LANGS = ['en', 'zh-Hant', 'zh-Hans'];
export const I18N = { lang: 'en' };

/** 依瀏覽器語言猜預設：台灣／香港 → 繁中，中國／新加坡 → 簡中，其他 → 英文 */
export function guessLang(nav) {
  const l = (nav || '').toLowerCase();
  if (/^zh-(tw|hk|mo|hant)/.test(l)) return 'zh-Hant';
  if (/^zh/.test(l)) return 'zh-Hans';
  return 'en';
}

export function t(key, p = {}) {
  const s = __DICT[I18N.lang]?.[key] ?? __DICT.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (p[k] ?? ''));
}

